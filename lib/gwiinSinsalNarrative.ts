export interface GwiinSinsalItem {
  name: string;
  body: string;
}

export interface GwiinSinsalSection {
  chapterLabel: string;
  title: string;
  intro: string;
  /** 무료 미리보기 — 사주팔자표 근처에 짧게 노출하는 1개(가장 먼저
   * 발견된 항목, PRIORITY_ORDER 기준 — 강약 점수화가 아니라 원고에
   * 나열된 고정 순서로 정한다). present 항목이 아예 없으면 undefined. */
  freePreview?: GwiinSinsalItem;
  /** 유료 섹션 "주요 해설" — 최대 3개, long 문단 */
  detail: GwiinSinsalItem[];
  /** 유료 섹션 "함께 들어 있는 기운" — detail에 들지 못한 나머지, short 문단 */
  brief: GwiinSinsalItem[];
  /** 신살 몇 줄로 갑자기 끝나는 느낌을 막기 위한 짧은 마무리 문단. 새 판정·
   * 새 문장 창작 없음 — 원고 전체가 반복해서 쓰는 "있다고 결과가 정해지는
   * 것은 아니다"라는 동일한 톤을 섹션 전체 단위로 한 번 더 반복할 뿐,
   * 특정 귀인/신살을 새로 언급하거나 위치·시기를 확장하지 않는다. */
  closing: string;
}

const MAX_DETAIL = 3;

/** 원고가 나열한 순서 그대로의 편집 우선순위. 명리적 강약을 계산하지
 * 않고, 이 고정 순서에서 실제로 있는 것만 앞에서부터 골라 쓴다. */
function buildOrderedSlots(user: SajuUser): TextEntry[] {
  const extra = analyzeExtraGwiin(user);
  const hasCheoneul = user.sinsal.includes("천을귀인");

  const slots: TextEntry[] = [];

  if (hasCheoneul) slots.push(GWIIN_TEXT.cheoneul);

  if (extra.munchang.present && extra.hakdang.present) {
    slots.push(MUNCHANG_HAKDANG_COMBO);
  } else {
    if (extra.munchang.present) slots.push(GWIIN_TEXT.munchang);
    if (extra.hakdang.present) slots.push(GWIIN_TEXT.hakdang);
  }

  if (extra.taeguk.present) slots.push(GWIIN_TEXT.taeguk);
  if (extra.woldeok.present) slots.push(GWIIN_TEXT.woldeok);
  if (extra.amrok.present) slots.push(GWIIN_TEXT.amrok);

  SINSAL_NAMES.forEach((name) => {
    if (user.sinsal.includes(name)) {
      const entry = SINSAL_TEXT[name];
      if (entry) slots.push(entry);
    }
  });

  return slots;
}

/**
 * 귀인·신살 해설 섹션을 만든다. 이 사람에게 실제로 있는 귀인·신살이
 * 하나도 없을 때만(이론상 발생하지 않지만 방어적으로) undefined를
 * 반환한다 — 없는 것을 지어내지 않는다.
 */
export function buildGwiinSinsalSection(user: SajuUser): GwiinSinsalSection | undefined {
  const slots = buildOrderedSlots(user);
  if (slots.length === 0) return undefined;

  const detailSlots = slots.slice(0, MAX_DETAIL);
  const briefSlots = slots.slice(MAX_DETAIL);

  return {
    chapterLabel: "第八章",
    title: `${user.name}님께 있는 귀인과 신살`,
    intro:
      "사주 여덟 글자 안에는 여러 기운이 함께 들어 있습니다. 그중 실제로 계산에서 확인된 것만 골라, 중복 없이 정리했습니다.",
    freePreview: slots[0] ? { name: slots[0].name, body: slots[0].short } : undefined,
    detail: detailSlots.map((s) => ({ name: s.name, body: s.long })),
    brief: briefSlots.map((s) => ({ name: s.name, body: s.short })),
    closing:
      `여기까지, ${user.name}님의 사주에서 실제로 확인된 귀인과 신살을 살펴봤습니다. ` +
      "어떤 기운이든 있다는 사실만으로 결과가 정해지는 것은 아니며, 평소 어떻게 지내고 어떤 선택을 하느냐에 따라 그 결이 달라질 수 있습니다.",
  };
}
