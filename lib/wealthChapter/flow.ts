const CHILDHOOD_END_AGE = 14;

const hasHiddenWealth = (p: DaYunWealthPeriod) => p.zhiHidden.some((z) => z.category === "재성") && p.ganCategory !== "재성";

export function generateFlowNewV7(key: ChapterFourKey): Result {
  const { past, current, next, priorWealthSignal } = key.daYun;
  const paras: NarrativeParagraph[] = [];
  // 과거·현재·다음·과거전 값이 하나도 없으면 ⑧ 본문을 만들지 않는다(값 생성 없음)
  if (!past && !current && !next && !priorWealthSignal) return { paragraphs: [] };
  const pc = past?.ganCategory ?? null, cc = current?.ganCategory ?? null, nc = next?.ganCategory ?? null;

  // ── 과거 ──
  const priorShown = !!priorWealthSignal && priorWealthSignal.endAge > CHILDHOOD_END_AGE;
  const p1: string[] = [];
  if (priorShown) p1.push(`${b("그보다 앞선 시기에는")} ${PRIOR_BODY[pc ?? "식상"]}`);
  if (past && pc) {
    const lead = priorShown ? "그 뒤 이어진 시기에는" : PAST_LEAD_NOPRIOR[pc];
    const body = priorShown && pc === "비겁" ? PAST_BODY_AFTER_PRIOR_비겁 : PAST_BODY[pc];
    p1.push(`${b(lead)} ${body}`);
    if (hasHiddenWealth(past)) p1.push(PAST_HN[pc]);
  }
  if (p1.length) paras.push({ text: p1.join(" "), sourceNote: "과거" });

  // ── 현재 ──
  if (current && cc) {
    const same = Boolean(pc && pc === cc);
    const parts: string[] = [];
    if (same) {
      const together = nc === "비겁" || nc === "관성";
      parts.push(b(cc === "재성" && together ? STAY_LEAD_재성_TOGETHER() : STAY_LEAD[cc]()), together ? STAY_TOGETHER[cc] : STAY_DIRECT[cc]);
    } else if (pc) {
      parts.push(b(`지금은 ${OPEN[cc]}`), CONTRAST[pc], NOW_MAIN[cc], NOW_EX[cc]);
      const br = BRIDGE(pc, cc); if (br) parts.push(br);
    } else {
      parts.push(b(`지금은 ${OPEN[cc]}`), NOW_MAIN[cc], NOW_EX[cc]);
    }
    let t = parts.join(" ");
    if (hasHiddenWealth(current) && !(next && hasHiddenWealth(next))) t += ` ${same ? HN_STAY(cc) : HN_CHANGE(cc)}`;
    paras.push({ text: t, sourceNote: same ? "현재(이어짐)" : "현재(바뀜)" });
  }

  // ── 다음 ──
  if (next && nc) {
    let t: string;
    if (cc && nc === cc) t = `${b(FUTSTAY_LEAD[nc])} ${FUTSTAY_BODY[nc]}`;
    else {
      const leadin = cc && (nc === "비겁" || nc === "재성") ? ` ${FUT_LEADIN[cc]}` : "";
      t = `${b(FUT_LEAD[nc])}${leadin} ${FUT_BODY[nc]}`;
    }
    if (hasHiddenWealth(next)) t += ` ${HN_NEXT(nc)}`;
    paras.push({ text: t, sourceNote: cc && nc === cc ? "다음(이어짐)" : "다음(바뀜)" });
  } else if (!next) {
    if (current && cc) paras.push({ text: pc && pc === cc ? CLOSE_STAY(cc) : CLOSE_CHANGE(cc), sourceNote: "마무리(다음 없음)" });
    // 현재도 없으면 마무리를 만들지 않는다(값이 전혀 없으면 paras는 빈 배열 → ⑧ 섹션 자체가 생기지 않음)
  }
  return { paragraphs: paras };
}
