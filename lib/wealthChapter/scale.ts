import { ChapterFourKey, buildChapterFourKey, compareCategories } from "../chapterFourInterpretation";

type Branch = "관성뚜렷" | "관성약간" | "재성뚜렷" | "재성약간" | "비슷강" | "비슷약";
export interface NarrativeParagraph { text: string; sourceNote: string }
export interface Result { branch: Branch; paragraphs: NarrativeParagraph[] }

export function classifyScale(key: ChapterFourKey): Branch {
  const cmp = compareCategories(key.wealth, "관성", "재성");
  if (cmp.gapTier === "비슷") {
    return Math.min(key.wealth.byCategory.관성.total, key.wealth.byCategory.재성.total) >= 3 ? "비슷강" : "비슷약";
  }
  if (cmp.leadCategory === "관성") return cmp.gapTier === "뚜렷" ? "관성뚜렷" : "관성약간";
  return cmp.gapTier === "뚜렷" ? "재성뚜렷" : "재성약간";
}

